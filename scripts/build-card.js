#!/usr/bin/env node
// Joins src/card/*.js, in the order of src/card/manifest.txt, into the one shipped card:
// custom_components/virtual_pet/frontend/hatch-pet-card.js (gitignored; unminified).
//
//   node scripts/build-card.js            build if the join differs; check every part
//   node scripts/build-card.js --where N  the part and line for line N of the BUILT file
//   node scripts/build-card.js --watch    rebuild on every change under src/card/
//
// Scripts and tests call ensureBuilt() (or join() for the text alone). It always joins and
// byte-compares with the built file, never mtime: a hand edit to the built file, or a
// worktree switched from a pre-move branch, leaves a newer file that is not the join.
"use strict";

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.join(__dirname, "..");
const SRC = path.join(ROOT, "src", "card");
const MANIFEST = path.join(SRC, "manifest.txt");
const OUT = path.join(ROOT, "custom_components", "virtual_pet", "frontend", "hatch-pet-card.js");
// sha256 of the last file this script wrote: tells an older join from a hand edit.
const STAMP = path.join(SRC, ".last-build.sha256");
const HEADER = "// GENERATED by scripts/build-card.js from src/card/. Edit src/, not this file.\n\n";

// The short git sha the card is built from, baked in where src/card/prefs.js has
// BUILD_PLACEHOLDER, so Settings can show which build runs. "dev" when git can't say
// (a source tree with no .git, e.g. an unpacked archive). Read once per process.
const BUILD_PLACEHOLDER = "__BUILD_SHA__";
let buildSha = null;
function gitSha() {
  if (buildSha === null) {
    try {
      buildSha = require("child_process").execFileSync("git", ["rev-parse", "--short=7", "HEAD"], {
        cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"],
      }).trim();
    } catch {}
    if (!/^[0-9a-f]{4,40}$/.test(buildSha || "")) buildSha = "dev";
  }
  return buildSha;
}

const sha = (s) => require("crypto").createHash("sha256").update(s).digest("hex");

function names() {
  const listed = fs.readFileSync(MANIFEST, "utf8").split("\n").map((l) => l.trim()).filter(Boolean);
  for (const f of listed) {
    if (!fs.existsSync(path.join(SRC, f))) throw new Error(`build-card: ${f} is in manifest.txt but not in src/card/`);
  }
  const unlisted = fs.readdirSync(SRC).filter((f) => f.endsWith(".js") && !listed.includes(f));
  if (unlisted.length) throw new Error(`build-card: not in src/card/manifest.txt: ${unlisted.join(", ")}`);
  return listed;
}

function parts() {
  return names().map((f) => {
    const text = fs.readFileSync(path.join(SRC, f), "utf8");
    if (!text.endsWith("\n")) throw new Error(`build-card: src/card/${f} does not end with a newline`);
    return { name: f, text: text.split(BUILD_PLACEHOLDER).join(gitSha()) };
  });
}

// The built card's text; writes nothing.
function join() {
  return HEADER + parts().map((p) => p.text).join("");
}

// Syntax only, like node --check: every part alone, then the whole card.
function check(text = join()) {
  for (const p of parts()) {
    try {
      new vm.Script(p.text, { filename: `src/card/${p.name}` });
    } catch (e) {
      throw new Error(`build-card: src/card/${p.name}: ${e.message}`);
    }
  }
  new vm.Script(text, { filename: OUT });
}

// Writes the join if the built file differs from it; returns the built path.
function ensureBuilt({ quiet = false } = {}) {
  const text = join();
  let old = null;
  try {
    old = fs.readFileSync(OUT, "utf8");
  } catch {}
  if (old === text) return OUT;
  check(text);
  if (old !== null) {
    let stamp = null;
    try {
      stamp = fs.readFileSync(STAMP, "utf8").trim();
    } catch {}
    if (sha(old) !== stamp) process.stderr.write(`build-card: ${path.relative(ROOT, OUT)}: built file was edited by hand; overwritten\n`);
  }
  // Temp file and rename: two builds at once never leave half a file.
  const tmp = `${OUT}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, text);
  fs.renameSync(tmp, OUT);
  fs.writeFileSync(STAMP, sha(text) + "\n");
  if (!quiet) process.stderr.write(`build-card: built ${path.relative(ROOT, OUT)}\n`);
  return OUT;
}

// Line N of the built file: [part, line in the part].
function where(n) {
  let at = HEADER.split("\n").length - 1;
  if (n <= at) return ["(GENERATED header)", n];
  for (const p of parts()) {
    const len = p.text.split("\n").length - 1;
    if (n <= at + len) return [`src/card/${p.name}`, n - at];
    at += len;
  }
  throw new Error(`build-card: line ${n} is past the end of the card (${at} lines)`);
}

module.exports = { HEADER, OUT, SRC, join, check, ensureBuilt, where };

if (require.main === module) {
  const args = process.argv.slice(2);
  try {
    if (args[0] === "--where") {
      const [p, n] = where(Number(args[1]));
      console.log(`${p}:${n}`);
    } else if (args[0] === "--watch") {
      ensureBuilt();
      let timer = null;
      fs.watch(SRC, () => {
        clearTimeout(timer);
        timer = setTimeout(() => {
          try {
            ensureBuilt();
          } catch (e) {
            console.error(e.message);
          }
        }, 100);
      });
      console.error("build-card: watching src/card/ (HA still needs a restart to serve a new card)");
    } else {
      ensureBuilt();
      check();
    }
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
